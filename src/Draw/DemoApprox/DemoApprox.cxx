static void KinkCurveD0(double t, double result[3])
{
  if (t <= M_PI) {
    result[0] = std::cos(t);
    result[1] = std::sin(t);
    result[2] = 0.0;
  } else {
    result[0] = std::cos(t);
    result[1] = -std::sin(t) + 2.0;
    result[2] = 0.5;
  }
}

class KinkCurveEvaluator : public AdvApprox_EvaluatorFunction
{
public:
  void Evaluate(int*    /*Dimension*/,
                double  /*StartEnd*/[2],
                double* Parameter,
                int*    DerivativeRequest,
                double* Result,
                int*    ErrorCode) override
  {
    double t  = *Parameter;
    int    d  = *DerivativeRequest;
    *ErrorCode = 0;

    double h = 1.0e-6;
    if (d == 0) {
      KinkCurveD0(t, Result);
    } else if (d == 1) {
      double r0[3], r1[3];
      KinkCurveD0(t - h, r0); KinkCurveD0(t + h, r1);
      for (int i = 0; i < 3; ++i) Result[i] = (r1[i] - r0[i]) / (2.0 * h);
    } else if (d == 2) {
      double r0[3], r1[3], r2[3];
      KinkCurveD0(t - h, r0); KinkCurveD0(t, r1); KinkCurveD0(t + h, r2);
      for (int i = 0; i < 3; ++i) Result[i] = (r0[i] - 2*r1[i] + r2[i]) / (h*h);
    }
  }
};

static void Demo7_CurveRebuildWithDiscontinuity()
{
  NCollection_Array1<double> pref(1, 1);  pref(1) = M_PI;
  NCollection_Array1<double> rec (1, 3);
  rec(1) = M_PI / 2.0;
  rec(2) = M_PI;
  rec(3) = 3.0 * M_PI / 2.0;

  AdvApprox_PrefAndRec cutter(pref, rec);
  KinkCurveEvaluator   evaluator;

  occ::handle<NCollection_HArray1<double>> tol1d = new NCollection_HArray1<double>(1,0);
  occ::handle<NCollection_HArray1<double>> tol2d = new NCollection_HArray1<double>(1,0);
  occ::handle<NCollection_HArray1<double>> tol3d = new NCollection_HArray1<double>(1,1);
  tol3d->SetValue(1, 1.0e-4);

  AdvApprox_ApproxAFunction approx(
    /*Num1D=*/0, /*Num2D=*/0, /*Num3D=*/1,
    tol1d, tol2d, tol3d,
    /*First=*/0.0, /*Last=*/2.0 * M_PI,
    /*Cont=*/GeomAbs_C0,
    /*MaxDeg=*/9,
    /*MaxSeg=*/20,
    evaluator, cutter);

  // Write input
  {
    ObjFile obj("demo7_input.obj");
    obj.group("kink_curve");
    obj.writeFunc([](double t) {
      double r[3]; KinkCurveD0(t, r);
      return gp_Pnt(r[0], r[1], r[2]);
    }, 0.0, 2.0 * M_PI);
  }

  if (approx.IsDone()) {
    std::cout << "Demo7 (kink curve rebuild):"
              << "  degree=" << approx.Degree()
              << "  nbKnots=" << approx.NbKnots()
              << "  maxErr=" << approx.MaxError(3, 1) << "\n";
    auto knots = approx.Knots();
    bool foundKink = false;
    for (int i = knots->Lower(); i <= knots->Upper(); ++i) {
      if (std::fabs(knots->Value(i) - M_PI) < 1.0e-8) { foundKink = true; break; }
    }
    std::cout << "  kink knot at pi found: " << (foundKink ? "YES" : "NO") << "\n";

    // Build BSpline curve from AdvApprox result
    auto poles3d = approx.Poles();
    auto knotsArr = approx.Knots();
    auto mults = approx.Multiplicities();
    int deg = approx.Degree();

    NCollection_Array1<gp_Pnt> bsPoles(1, poles3d->ColLength());
    for (int i = 1; i <= poles3d->ColLength(); ++i)
      bsPoles(i) = poles3d->Value(i, 1);

    NCollection_Array1<double> bsKnots(knotsArr->Lower(), knotsArr->Upper());
    for (int i = knotsArr->Lower(); i <= knotsArr->Upper(); ++i)
      bsKnots(i) = knotsArr->Value(i);

    NCollection_Array1<int> bsMults(mults->Lower(), mults->Upper());
    for (int i = mults->Lower(); i <= mults->Upper(); ++i)
      bsMults(i) = mults->Value(i);

    occ::handle<Geom_BSplineCurve> resultCurve =
      new Geom_BSplineCurve(bsPoles, bsKnots, bsMults, deg);

    ObjFile obj("demo7_output.obj");
    obj.group("result_curve");
    obj.writeCurve(resultCurve);

    ObjFile objCtrl("demo7_ctrl.obj");
    objCtrl.writeCtrlPoly(resultCurve);
  } else {
    std::cout << "Demo7: HasResult=" << approx.HasResult() << "\n";
  }
  std::cout << "  -> demo7_input.obj, demo7_output.obj, demo7_ctrl.obj\n";
}

