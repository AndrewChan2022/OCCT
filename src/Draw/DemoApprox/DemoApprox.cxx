struct ObjFile {
  std::ofstream f;
  int vcount = 0;

  ObjFile(const std::string& path) : f(path) {
    f << "# Generated by DemoApprox\n";
  }
  ~ObjFile() { f.close(); }

  void group(const char* name) { f << "g " << name << "\n"; }

  int vertex(const gp_Pnt& p) {
    f << "v " << p.X() << " " << p.Y() << " " << p.Z() << "\n";
    return ++vcount;
  }

  // Write a polyline as consecutive 2-vertex line segments
  void writePolyline(const std::vector<gp_Pnt>& pts) {
    if (pts.size() < 2) return;
    int base = vcount;
    for (auto& p : pts) vertex(p);
    for (int i = 0; i < (int)pts.size() - 1; ++i)
      f << "l " << (base + i + 1) << " " << (base + i + 2) << "\n";
  }

  // Write BSpline curve control points and control polygon
  void writeCtrlPoly(const occ::handle<Geom_BSplineCurve>& C) {
    if (C.IsNull()) return;
    int nP = C->NbPoles();
    group("ctrl_points");
    int base = vcount;
    for (int i = 1; i <= nP; ++i) vertex(C->Pole(i));
    for (int i = 0; i < nP; ++i)
      f << "p " << (base + i + 1) << "\n";
    group("ctrl_polygon");
    for (int i = 0; i < nP - 1; ++i)
      f << "l " << (base + i + 1) << " " << (base + i + 2) << "\n";
  }

  // Write BSpline surface control points and control net
  void writeCtrlNet(const occ::handle<Geom_BSplineSurface>& S) {
    if (S.IsNull()) return;
    int nU = S->NbUPoles(), nV = S->NbVPoles();
    group("ctrl_points");
    int base = vcount;
    for (int i = 1; i <= nU; ++i)
      for (int j = 1; j <= nV; ++j)
        vertex(S->Pole(i, j));
    for (int i = 0; i < nU * nV; ++i)
      f << "p " << (base + i + 1) << "\n";
    group("ctrl_net_u");
    for (int i = 0; i < nU; ++i)
      for (int j = 0; j < nV - 1; ++j) {
        int v0 = base + i * nV + j + 1;
        f << "l " << v0 << " " << (v0 + 1) << "\n";
      }
    group("ctrl_net_v");
    for (int j = 0; j < nV; ++j)
      for (int i = 0; i < nU - 1; ++i) {
        int v0 = base + i * nV + j + 1;
        int v1 = base + (i + 1) * nV + j + 1;
        f << "l " << v0 << " " << v1 << "\n";
      }
  }

  // Sample a parametric function and write as polyline
  void writeFunc(const std::function<gp_Pnt(double)>& func,
                 double t0, double t1, int nSamples = 200) {
    std::vector<gp_Pnt> pts;
    for (int i = 0; i <= nSamples; ++i) {
      double t = t0 + (t1 - t0) * i / nSamples;
      pts.push_back(func(t));
    }
    writePolyline(pts);
  }

  // Sample a BSpline curve and write as polyline
  void writeCurve(const occ::handle<Geom_BSplineCurve>& C, int nSamples = 200) {
    if (C.IsNull()) return;
    double u0 = C->FirstParameter(), u1 = C->LastParameter();
    writeFunc([&](double u) { gp_Pnt p; C->D0(u, p); return p; },
              u0, u1, nSamples);
  }

  // Sample a parametric surface function and write as triangle mesh
  void writeFuncSurf(const std::function<gp_Pnt(double, double)>& func,
                     double u0, double u1, double v0, double v1,
                     int nu = 40, int nv = 40) {
    int base = vcount;
    for (int i = 0; i <= nu; ++i) {
      double u = u0 + (u1 - u0) * i / nu;
      for (int j = 0; j <= nv; ++j) {
        double v = v0 + (v1 - v0) * j / nv;
        vertex(func(u, v));
      }
    }
    for (int i = 0; i < nu; ++i) {
      for (int j = 0; j < nv; ++j) {
        int v00 = base + i * (nv + 1) + j + 1;
        int v10 = base + (i + 1) * (nv + 1) + j + 1;
        int v01 = v00 + 1;
        int v11 = v10 + 1;
        f << "f " << v00 << " " << v10 << " " << v11 << "\n";
        f << "f " << v00 << " " << v11 << " " << v01 << "\n";
      }
    }
  }

  // Sample a BSpline surface and write as triangle mesh
  void writeSurface(const occ::handle<Geom_BSplineSurface>& S,
                    int nu = 40, int nv = 40) {
    if (S.IsNull()) return;
    double u0 = S->UKnot(1), u1 = S->UKnot(S->NbUKnots());
    double v0 = S->VKnot(1), v1 = S->VKnot(S->NbVKnots());
    writeFuncSurf([&](double u, double v) {
      gp_Pnt p; S->D0(u, v, p); return p;
    }, u0, u1, v0, v1, nu, nv);
  }
};

